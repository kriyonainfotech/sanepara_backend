import { DailyTaskRule } from '../models/DailyTaskRule.js';
import { Task } from '../models/Task.js';
import { User } from '../models/User.js';
import { Customer } from '../models/Customer.js';
import { ChecklistTemplate } from '../models/ChecklistTemplate.js';
import { dayKey, isSunday } from '../utils/dates.js';

const istHour = () => Number(new Intl.DateTimeFormat('en-GB', { timeZone: 'Asia/Kolkata', hour: '2-digit', hour12: false }).format(new Date()));
const tomorrowKey = () => dayKey(new Date(Date.now() + 24 * 60 * 60 * 1000));
const lastDayOf = (y, m) => new Date(Date.UTC(y, m, 0)).getUTCDate(); // m is 1-12

export function ruleRunsOn(rule, day) {
  const d = new Date(`${day}T00:00:00Z`);
  const [y, m, date] = [d.getUTCFullYear(), d.getUTCMonth() + 1, d.getUTCDate()];
  switch (rule.frequency || 'Daily') {
    case 'Daily':
      return true;
    case 'Weekly':
      return (rule.daysOfWeek || []).map(Number).includes(d.getUTCDay());
    case 'Monthly':
      return date === Math.min(rule.dateOfMonth || 1, lastDayOf(y, m));
    case 'Yearly':
      return m === (rule.monthOfYear || 1) && date === Math.min(rule.dateOfMonth || 1, lastDayOf(y, m));
    default:
      return false;
  }
}

// Create the rule's tasks for one day. Returns how many were created.
export async function generateForRule(rule, day, createdBy) {
  const assignee = await User.findById(rule.assignedTo).select('role isActive');
  if (!assignee?.isActive) return 0;
  const type = assignee.role === 'team' ? 'Team' : 'Personal';
  const base = {
    description: rule.description || `Generated by Daily Task Rule: ${rule.title}`,
    type,
    taskCategory: 'Daily Task',
    isDailyTask: true,
    status: 'Pending',
    dueDate: day,
    assignedTo: rule.assignedTo,
    createdBy: createdBy || rule.createdBy,
    dailyRule: rule._id,
  };

  if (rule.isChecklistTask) {
    let items = rule.customChecklist || [];
    if (!items.length && rule.checklistTemplate) items = (await ChecklistTemplate.findById(rule.checklistTemplate))?.items || [];
    base.checklist = items.map((text) => ({ text, isCompleted: false }));
    base.requiresChecklistCompletion = items.length > 0;
    // No customers: a single checklist task. With customers: one checklist task each (below).
    if (!rule.clients?.length) {
      await Task.create({ ...base, title: rule.title });
      return 1;
    }
  }

  const clients = await Customer.find({ _id: { $in: rule.clients } }).select('businessName');
  if (!clients.length) return 0;
  await Task.insertMany(clients.map((c) => ({ ...base, title: `${rule.title} - ${c.businessName}`, client: c._id })));
  return clients.length;
}

// Every evening from 7 PM (India time) create tomorrow's tasks, never for Sunday.
// `lastGeneratedFor` keeps it to once per rule per day, even across restarts.
export async function runDailyTaskJob() {
  if (istHour() < 19) return;
  const day = tomorrowKey();
  const rules = await DailyTaskRule.find({ isActive: true, lastGeneratedFor: { $ne: day } });
  let created = 0;
  for (const rule of rules) {
    if (!isSunday(day) && ruleRunsOn(rule, day)) created += await generateForRule(rule, day);
    rule.lastGeneratedFor = day;
    await rule.save();
  }
  if (created) console.log(`[Daily tasks] Created ${created} tasks for ${day}`);
}

export function startDailyTaskScheduler() {
  const run = () => runDailyTaskJob().catch((e) => console.error('[Daily tasks] Failed:', e.message));
  run();
  setInterval(run, 60 * 1000);
}
